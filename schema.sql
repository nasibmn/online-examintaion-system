CREATE DATABASE IF NOT EXISTS userinformation CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE userinformation;

CREATE TABLE IF NOT EXISTS usertable (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  adsoyad VARCHAR(100) NOT NULL,
  cinsiyet VARCHAR(20) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  Email VARCHAR(190) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS teacher_table (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  adsoyad VARCHAR(100) NOT NULL,
  Email VARCHAR(190) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS subjects (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  ders_adi VARCHAR(100) NOT NULL,
  AKTS VARCHAR(5) NOT NULL,
  dersin_koordinatoru VARCHAR(100) NOT NULL,
  sinav_suresi INT UNSIGNED NOT NULL DEFAULT 30,
  soru_sayisi INT UNSIGNED NOT NULL DEFAULT 10,
  dogru_cevap_puani INT UNSIGNED NOT NULL DEFAULT 10,
  yanlis_cevap_puani INT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS questions (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  ders_kodu INT UNSIGNED NOT NULL,
  soru TEXT NOT NULL,
  FOREIGN KEY (ders_kodu) REFERENCES subjects(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS question_options (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  soru_kodu INT UNSIGNED NOT NULL,
  shk1 VARCHAR(255) NOT NULL,
  shk2 VARCHAR(255) NOT NULL,
  shk3 VARCHAR(255) NOT NULL,
  shk4 VARCHAR(255) NOT NULL,
  dogru_cevap TINYINT UNSIGNED NOT NULL,
  FOREIGN KEY (soru_kodu) REFERENCES questions(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS exam_attempts (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  student_id INT UNSIGNED NOT NULL,
  subject_id INT UNSIGNED NOT NULL,
  correct_answers INT UNSIGNED NOT NULL DEFAULT 0,
  wrong_answers INT UNSIGNED NOT NULL DEFAULT 0,
  unanswered INT UNSIGNED NOT NULL DEFAULT 0,
  score INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (student_id) REFERENCES usertable(id) ON DELETE CASCADE,
  FOREIGN KEY (subject_id) REFERENCES subjects(id) ON DELETE CASCADE
) ENGINE=InnoDB;
